//! The user guide's generated reference pages (docs/specs/user-guide.md §4): the command
//! line from the clap definitions, the file formats from their JSON Schemas. A test keeps
//! the committed pages equal to these.

use std::fmt::Write as _;

use clap::Command;
use serde_json::{Map, Value};

const GENERATED: &str = "<!-- Generated by `chipload reference`; do not edit. Regenerate with \
                         CHIPLOAD_UPDATE_GOLDEN=1 cargo test -p chipload-cli --test guide. -->";

/// One line: newlines and table pipes made safe for a Markdown table cell.
fn cell(text: &str) -> String {
    let joined = text.split_whitespace().collect::<Vec<_>>().join(" ");
    joined.replace('|', "\\|")
}

/// The command-line reference: every visible command, with its arguments.
pub fn cli_page(root: &Command) -> String {
    let mut page = format!("# Command line\n\n{GENERATED}\n\n");
    let _ = writeln!(
        page,
        "Every command takes `--json`: one JSON object instead of text (see \
         [Scripting](../scripting.md)). `chipload --help` and `chipload COMMAND --help` print \
         the same help in the terminal.\n"
    );
    for sub in visible(root) {
        command_section(&mut page, &[], sub);
    }
    page
}

/// The subcommands to document: not hidden, and not clap's own `help`.
fn visible(cmd: &Command) -> impl Iterator<Item = &Command> {
    cmd.get_subcommands()
        .filter(|c| !c.is_hide_set() && c.get_name() != "help")
}

fn command_section(page: &mut String, parents: &[&str], cmd: &Command) {
    let mut path: Vec<&str> = parents.to_vec();
    path.push(cmd.get_name());
    let name = format!("chipload {}", path.join(" "));
    let subcommands: Vec<&Command> = visible(cmd).collect();
    let level = if parents.is_empty() { "##" } else { "###" };
    let _ = writeln!(page, "{level} `{name}`\n");
    if let Some(about) = cmd.get_long_about().or(cmd.get_about()) {
        let _ = writeln!(page, "{}\n", about.to_string().trim());
    }
    if !subcommands.is_empty() {
        for sub in subcommands {
            command_section(page, &path, sub);
        }
        return;
    }
    let args: Vec<&clap::Arg> = cmd
        .get_arguments()
        .filter(|a| !a.is_hide_set() && !a.is_global_set())
        .filter(|a| !matches!(a.get_id().as_str(), "help" | "version"))
        .collect();
    let positionals: Vec<String> = args
        .iter()
        .filter(|a| a.is_positional())
        .map(|a| {
            let mut text = format!("<{}>", a.get_id().as_str().to_uppercase());
            if a.get_num_args().is_some_and(|n| n.max_values() > 1) {
                text.push_str("...");
            }
            text
        })
        .collect();
    let mut usage = name.clone();
    for p in &positionals {
        usage.push(' ');
        usage.push_str(p);
    }
    if args.iter().any(|a| !a.is_positional()) {
        usage.push_str(" [OPTIONS]");
    }
    let _ = writeln!(page, "```text\n{usage}\n```\n");
    if args.is_empty() {
        return;
    }
    page.push_str("| Argument | Meaning |\n|---|---|\n");
    for arg in args {
        let _ = writeln!(page, "| {} | {} |", arg_name(arg), arg_help(arg));
    }
    page.push('\n');
}

fn arg_name(arg: &clap::Arg) -> String {
    if arg.is_positional() {
        return format!("`<{}>`", arg.get_id().as_str().to_uppercase());
    }
    let mut names = Vec::new();
    if let Some(short) = arg.get_short() {
        names.push(format!("-{short}"));
    }
    if let Some(long) = arg.get_long() {
        names.push(format!("--{long}"));
    }
    let takes_value = arg.get_num_args().is_some_and(|n| n.takes_values());
    let mut text = names.join(", ");
    if takes_value {
        let value = arg
            .get_value_names()
            .and_then(|v| v.first())
            .map_or_else(|| arg.get_id().as_str().to_uppercase(), |v| v.to_string());
        let _ = write!(text, " <{value}>");
    }
    format!("`{text}`")
}

fn arg_help(arg: &clap::Arg) -> String {
    let mut text = arg
        .get_long_help()
        .or(arg.get_help())
        .map(|h| cell(&h.to_string()))
        .unwrap_or_default();
    // Clap's help lines often end without a full stop; more follows here.
    if !text.is_empty() && !text.ends_with(['.', ')', '!', '?']) {
        text.push('.');
    }
    let values: Vec<String> = arg
        .get_possible_values()
        .iter()
        .filter(|v| !v.is_hide_set())
        .map(|v| match v.get_help() {
            Some(help) => format!("`{}` ({})", v.get_name(), cell(&help.to_string())),
            None => format!("`{}`", v.get_name()),
        })
        .collect();
    let is_flag = !arg.get_num_args().is_some_and(|n| n.takes_values());
    if !values.is_empty() && !is_flag {
        let _ = write!(text, " One of: {}.", values.join(", "));
    }
    let defaults: Vec<String> = arg
        .get_default_values()
        .iter()
        .map(|d| d.to_string_lossy().into_owned())
        .collect();
    if !defaults.is_empty() && !is_flag {
        let _ = write!(text, " Default: `{}`.", defaults.join(" "));
    }
    if arg.is_required_set() && !arg.is_positional() {
        text.push_str(" Required.");
    }
    let repeats = matches!(arg.get_action(), clap::ArgAction::Append)
        || arg.get_num_args().is_some_and(|n| n.max_values() > 1);
    if repeats && !arg.is_positional() {
        text.push_str(" Repeatable.");
    }
    text.trim().to_string()
}

/// A file format's reference from its JSON Schema: the top level, then every definition.
pub fn schema_page(title: &str, intro: &str, schema: &Value) -> String {
    let mut page = format!("# {title}\n\n{GENERATED}\n\n{intro}\n\n");
    if let Some(description) = schema.get("description").and_then(Value::as_str) {
        let _ = writeln!(page, "{}\n", description.trim());
    }
    page.push_str("## The file\n\n");
    object_table(&mut page, schema);
    let defs = schema
        .get("$defs")
        .and_then(Value::as_object)
        .cloned()
        .unwrap_or_default();
    for (name, def) in &defs {
        definition(&mut page, name, def);
    }
    page
}

fn definition(page: &mut String, name: &str, def: &Value) {
    let _ = writeln!(page, "## {name}\n");
    if let Some(description) = def.get("description").and_then(Value::as_str) {
        let _ = writeln!(page, "{}\n", paragraph(description));
    }
    if def.get("properties").is_some() {
        object_table(page, def);
        return;
    }
    if let Some(values) = def.get("enum").and_then(Value::as_array) {
        let names: Vec<String> = values.iter().map(|v| format!("`{v}`")).collect();
        let _ = writeln!(page, "One of: {}.\n", names.join(", "));
        return;
    }
    let variants = def
        .get("oneOf")
        .or_else(|| def.get("anyOf"))
        .and_then(Value::as_array);
    for variant in variants.into_iter().flatten() {
        variant_section(page, variant);
    }
}

/// One choice of an enum: a tagged object (`"type": "…"` and its fields) or a plain value.
fn variant_section(page: &mut String, variant: &Value) {
    let description = variant
        .get("description")
        .and_then(Value::as_str)
        .map(paragraph);
    let tag = variant
        .pointer("/properties/type/const")
        .or_else(|| variant.get("const"));
    let values = variant.get("enum").and_then(Value::as_array);
    match (tag, values) {
        (Some(tag), _) if variant.get("properties").is_some() => {
            let _ = writeln!(page, "### `\"type\": {tag}`\n");
            if let Some(d) = description {
                let _ = writeln!(page, "{d}\n");
            }
            let mut fields = variant.clone();
            if let Some(props) = fields.get_mut("properties").and_then(Value::as_object_mut) {
                props.remove("type");
            }
            if fields
                .get("properties")
                .and_then(Value::as_object)
                .is_some_and(|p| !p.is_empty())
            {
                object_table(page, &fields);
            }
        }
        (Some(value), _) => {
            let _ = writeln!(page, "- `{value}`: {}", description.unwrap_or_default());
            page.push('\n');
        }
        (None, Some(values)) => {
            let names: Vec<String> = values.iter().map(|v| format!("`{v}`")).collect();
            let _ = writeln!(
                page,
                "- {}: {}\n",
                names.join(", "),
                description.unwrap_or_default()
            );
        }
        (None, None) => {
            let _ = writeln!(
                page,
                "- {}: {}\n",
                type_text(variant),
                description.unwrap_or_default()
            );
        }
    }
}

fn object_table(page: &mut String, object: &Value) {
    let empty = Map::new();
    let props = object
        .get("properties")
        .and_then(Value::as_object)
        .unwrap_or(&empty);
    let required: Vec<&str> = object
        .get("required")
        .and_then(Value::as_array)
        .map(|r| r.iter().filter_map(Value::as_str).collect())
        .unwrap_or_default();
    page.push_str("| Field | Type | Required | Meaning |\n|---|---|---|---|\n");
    for (name, prop) in props {
        let meaning = prop
            .get("description")
            .and_then(Value::as_str)
            .map(cell)
            .unwrap_or_default();
        let _ = writeln!(
            page,
            "| `{name}` | {} | {} | {meaning} |",
            type_text(prop),
            if required.contains(&name.as_str()) {
                "yes"
            } else {
                "no"
            }
        );
    }
    page.push('\n');
}

fn paragraph(text: &str) -> String {
    // Keep the blank lines between paragraphs, join the wrapped lines of each.
    text.split("\n\n")
        .map(|p| p.split_whitespace().collect::<Vec<_>>().join(" "))
        .collect::<Vec<_>>()
        .join("\n\n")
}

/// A schema's type in words: "number", "[`Tool`](#tool) list", "string or null", …
fn type_text(v: &Value) -> String {
    if let Some(reference) = v.get("$ref").and_then(Value::as_str) {
        let name = reference.rsplit('/').next().unwrap_or(reference);
        return format!("[{name}](#{})", name.to_lowercase());
    }
    if let Some(constant) = v.get("const") {
        return format!("`{constant}`");
    }
    if let Some(values) = v.get("enum").and_then(Value::as_array) {
        let names: Vec<String> = values.iter().map(|v| format!("`{v}`")).collect();
        return names.join(" or ");
    }
    if let Some(any) = v
        .get("anyOf")
        .or_else(|| v.get("oneOf"))
        .and_then(Value::as_array)
    {
        let parts: Vec<String> = any.iter().map(type_text).collect();
        return parts.join(" or ");
    }
    let types: Vec<&str> = match v.get("type") {
        Some(Value::String(t)) => vec![t.as_str()],
        Some(Value::Array(ts)) => ts.iter().filter_map(Value::as_str).collect(),
        _ => Vec::new(),
    };
    let words: Vec<String> = types
        .iter()
        .map(|t| match *t {
            "array" => array_text(v),
            "integer" => "integer".to_string(),
            "number" => "number".to_string(),
            other => other.to_string(),
        })
        .collect();
    if words.is_empty() {
        "any".to_string()
    } else {
        words.join(" or ")
    }
}

fn array_text(v: &Value) -> String {
    let item = v
        .get("items")
        .map(type_text)
        .unwrap_or_else(|| "any".into());
    let fixed = v
        .get("minItems")
        .zip(v.get("maxItems"))
        .filter(|(a, b)| a == b);
    match fixed {
        Some((n, _)) => format!("{n} × {item}"),
        None => format!("list of {item}"),
    }
}
